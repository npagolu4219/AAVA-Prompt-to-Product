function htmlProject(opts: ExportOptions, screens: ScreenCtx[], theme: ThemeSettings): { files: GenFile[]; notes: string[] } {
  const notes = ['Static export: collections were rendered from the database seed at export time.']
  const sections = screens
    .map((s) => `      <section class="screen" data-route="${s.route}" aria-label="${escapeHtml(s.title)}" hidden>\n${toHtml(s.ir.root, 4, s.ir.seed)}\n      </section>`)
    .join('\n\n')
  const routes = Object.fromEntries(screens.map((s) => [s.route, s.routes]))
  const files: GenFile[] = [
    file(
      'index.html',
      `<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n    <link rel="icon" href="data:," />\n    <title>${escapeHtml(opts.projectName)}</title>\n    <link rel="stylesheet" href="assets/tokens.css" />\n    <link rel="stylesheet" href="assets/aava-play.css" />\n    <link rel="stylesheet" href="assets/app.css" />\n  </head>\n  <body>\n    <div class="app-shell">\n      <nav class="app-nav" aria-label="Screens">\n        <span class="app-nav__brand">${escapeHtml(opts.projectName)}</span>\n        <div class="app-nav__links">\n${screens.map((s) => `          <a class="app-nav__link" href="#${s.route}">${escapeHtml(s.title)}</a>`).join('\n')}\n        </div>\n      </nav>\n      <main class="app-main">\n${sections}\n      </main>\n    </div>\n    <script src="assets/app.js" defer></script>\n  </body>\n</html>\n`,
    ),
    file('assets/tokens.css', tokensCss(theme)),
    file('assets/aava-play.css', AAVA_PLAY_CSS),
    file('assets/app.css', `${SHELL_CSS}\n.screen[hidden] { display: none; }\n`),
    file(
      'assets/app.js',
      `// Generated by AAVA Prompt-to-Product — hash router, form model and flow navigation.\n(function () {\n  'use strict';\n  var ROUTES = ${JSON.stringify(routes, null, 2).replace(/\n/g, '\n  ')};\n  var DEFAULT_ROUTE = '${screens[0]?.route ?? '/'}';\n  var model = {};\n\n  function show() {\n    var path = location.hash.slice(1) || DEFAULT_ROUTE;\n    var found = false;\n    document.querySelectorAll('[data-route]').forEach(function (el) {\n      var match = el.getAttribute('data-route') === path;\n      el.hidden = !match;\n      if (match) found = true;\n    });\n    if (!found) return void (location.hash = '#' + DEFAULT_ROUTE);\n    document.querySelectorAll('.app-nav__link').forEach(function (a) {\n      a.classList.toggle('is-active', a.getAttribute('href') === '#' + path);\n    });\n    window.scrollTo(0, 0);\n  }\n\n  document.addEventListener('input', function (e) {\n    var t = e.target;\n    var key = t && t.getAttribute && t.getAttribute('data-model');\n    if (key) model[key] = t.type === 'checkbox' ? t.checked : t.value;\n  });\n\n  document.addEventListener('click', function (e) {\n    var el = e.target.closest && e.target.closest('[data-action]');\n    if (!el) return;\n    var screen = el.closest('[data-route]').getAttribute('data-route');\n    var action = el.getAttribute('data-action');\n    var to = (ROUTES[screen] || {})[action];\n    if (to) location.hash = '#' + to;\n    else window.dispatchEvent(new CustomEvent('aava:action', { detail: { screen: screen, action: action, model: model } }));\n  });\n\n  window.addEventListener('hashchange', show);\n  show();\n})();\n`,
    ),
    ...(opts.includeData ? screens.map((s) => file(`data/${s.screen.slug}.json`, json(s.ir.seed))) : []),
  ]
  // Always ship a package.json so `npm install && npm start` works like the framework stacks.
  files.push(file('package.json', json({ name: opts.projectName, version: '0.1.0', private: true, engines: ENGINES, scripts: { start: 'serve -l 3000 .', build: 'echo "Static site — no build step"', ...testScripts(opts) }, devDependencies: { serve: '^14.2.5', ...testDeps(opts) } })))
  if (opts.apiUrl) notes.push(`API_URL ${opts.apiUrl} is ignored for static HTML (collections are pre-rendered).`)
  files.push(...commonFiles(opts, STACKS[3], screens, { dist: '.', urlFor: (r) => `/#${r}`, buildCmd: '' }))
  return { files, notes }
}

