interface ScreenCtx {
  screen: ScreenState
  ir: ScreenIR
  pascal: string
  title: string
  route: string
  routes: Record<string, string>
  heading: string
  hasModel: boolean
}

const json = (v: unknown) => JSON.stringify(v, null, 2) + '\n'
const file = (path: string, content: string): GenFile => ({ path, content, language: languageForPath(path) })

function walk(n: IRNode, fn: (n: IRNode) => void) {
  fn(n)
  if (n.k === 'el') n.children?.forEach((c) => walk(c, fn))
  if (n.k === 'each') walk(n.child, fn)
}

function screenContexts(screens: ScreenState[]): ScreenCtx[] {
  const included = new Map(screens.map((s) => [s.id, s]))
  const usedNames = new Set<string>()
  return screens.map((screen) => {
    const ir = buildScreenIR(screen)
    let pascal = toPascal(screen.slug) || 'Screen'
    if (/^\d/.test(pascal)) pascal = `Screen${pascal}`
    while (usedNames.has(pascal)) pascal += '2'
    usedNames.add(pascal)
    let hasModel = false
    walk(ir.root, (n) => {
      if (n.k === 'el' && n.model) hasModel = true
    })
    const heading = Object.values(screen.surface?.components ?? {}).find((c) => c.component === 'AavaHeading')
    return {
      screen,
      ir,
      pascal,
      title: screen.shared.title || pascal,
      route: screen.route,
      routes: Object.fromEntries(screen.links.filter((l) => included.has(l.targetId)).map((l) => [l.action, included.get(l.targetId)!.route])),
      heading: String(heading?.text ?? screen.shared.title),
      hasModel,
    }
  })
}

