import type { A2uiComponent } from '@/types/a2ui'
import type { CollectionBinding, QualityReport, RunSource } from '@/types/run'
import type { Scenario, ScenarioPlan } from '@/types/scenario'
import { DECISION_COPY } from '@/services/quality/scoring'

export interface SpecInput {
  scenario: Scenario
  plan: ScenarioPlan
  planNotes: string[]
  components: A2uiComponent[]
  dataModel: Record<string, unknown>
  version: number
  source: RunSource
  quality: QualityReport | null
  changelog: string[]
  bindings?: CollectionBinding[]
  route?: string
  /** Context resources (codebase, Figma library, docs…) the agents grounded on. */
  context?: string[]
}

const KEY_PROPS = ['text', 'label', 'title', 'variant', 'level', 'columns', 'type', 'tone']

const propsSummary = (c: A2uiComponent) =>
  KEY_PROPS.filter((k) => c[k] !== undefined && c[k] !== '')
    .map((k) => `${k}=${String(c[k]).replace(/\|/g, '\\|')}`)
    .join(', ') || '—'

/** Generates the human-readable screen spec + audit report (rendered in the Spec tab). */
export function generateSpec(i: SpecInput): string {
  const { scenario: s, quality: q } = i
  const comps = i.components.filter((c) => !['Column', 'Row', 'Grid'].includes(c.component))
  const lines: string[] = [
    `# ${s.title} — Screen Spec`,
    '',
    `> Generated by **AAVA Prompt-to-Product** · version **v${i.version}** · ${new Date().toLocaleString()}`,
    '',
    '## 1. Overview',
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Screen type | \`${s.intent.screenType}\` |`,
    `| Source | ${i.source.kind === 'figma' ? `Figma — ${i.source.label}` : 'Prompt'} |`,
    `| Components | ${comps.length} AAVA Play instances (${new Set(comps.map((c) => c.component)).size} types) |`,
    `| Route | \`${i.route ?? '/'}\` |`,
    `| Grounded on | ${i.context?.length ? [...new Set(i.context)].join(', ') : 'AAVA defaults'} |`,
    `| Output | Angular 21 standalone component · SCSS · Playwright spec |`,
    '',
    '## 2. Intent',
    '',
    '```json',
    JSON.stringify(s.intent, null, 2),
    '```',
    '',
    '## 3. Component inventory',
    '',
    '| ID | Component | Key props |',
    '| --- | --- | --- |',
    ...comps.map((c) => `| \`${c.id}\` | ${c.component.startsWith('Aava') ? c.component : `⚠ ${c.component}`} | ${propsSummary(c)} |`),
    '',
    '## 4. Layout plan',
    '',
    `${i.plan.summary}`,
    '',
    ...i.plan.items.map((x) => `- ${x}`),
    ...(i.planNotes.length ? ['', '**Reviewer notes (HITL ①):**', ...i.planNotes.map((n) => `- ${n}`)] : []),
    '',
    '## 5. Responsive behaviour',
    '',
    ...s.responsive.map((x) => `- ${x}`),
    '',
    '## 6. States',
    '',
    ...s.states.map((x) => `- [ ] ${x}`),
    '',
    '## 7. Data model',
    '',
    '```json',
    JSON.stringify(i.dataModel, null, 2),
    '```',
    '',
  ]

  lines.push('## 8. Data sources', '')
  if (i.bindings?.length)
    lines.push(
      '| Component | Prop | Table | Source | Rows |',
      '| --- | --- | --- | --- | ---: |',
      ...i.bindings.map((b) => `| \`${b.componentId}\` | ${b.prop} | \`${b.table}\` | ${b.source} | ${b.rowCount} |`),
      '',
      '_Generated code fetches these collections from `GET {API}/collections/{table}` and falls back to the seed values above._',
      '',
    )
  else lines.push('_Static content — no database collections bound._', '')

  lines.push('## 9. Quality report', '')
  if (!q) {
    lines.push('_Verification pending — Critic, Audit, Lint and Playwright run after codegen._', '')
  } else {
    lines.push(
      `**Score:** \`${q.score.toFixed(2)}\` · **Iteration:** ${q.iteration} · **Decision:** ${DECISION_COPY[q.decision].label}`,
      '',
      '| Dimension | Weight | Score |',
      '| --- | ---: | ---: |',
      ...q.dimensions.map((d) => `| ${d.label} | ${Math.round(d.weight * 100)}% | ${d.score.toFixed(2)} |`),
      '',
      '### Hard gates',
      '',
      ...q.hardGates.map((g) => `- ${g.passed ? '✅' : '❌'} ${g.label}`),
      '',
      '### Gap report',
      '',
    )
    if (q.gaps.length === 0) lines.push('No open gaps. 🎉', '')
    else
      lines.push(
        '| Element | Property | Found | Expected | Rule | Fix | Source |',
        '| --- | --- | --- | --- | --- | --- | --- |',
        ...q.gaps.map((g) => `| \`${g.el}\` | ${g.prop} | \`${g.found}\` | \`${g.expected}\` | ${g.rule} | ${g.fix} | ${g.source} |`),
        '',
      )
  }

  lines.push('## 10. Changelog', '', ...(i.changelog.length ? i.changelog.map((c) => `- ${c}`) : ['- v1 — initial generation']), '')
  return lines.join('\n')
}
