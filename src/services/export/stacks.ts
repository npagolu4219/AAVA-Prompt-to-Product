export interface BuiltProject {
  files: GenFile[]
  routes: { path: string; title: string }[]
  notes: string[]
}

export function buildProject(opts: ExportOptions, allScreens: ScreenState[], theme: ThemeSettings): BuiltProject {
  const chosen = allScreens.filter((s) => opts.screenIds.includes(s.id) && s.surface)
  const screens = screenContexts(chosen)
  const builder = { angular: angularProject, react: reactProject, vue: vueProject, html: htmlProject }[opts.stack]
  const { files, notes } = builder(opts, screens, theme)
  return {
    files: files.sort((a, b) => a.path.localeCompare(b.path)),
    routes: screens.map((s) => ({ path: s.route, title: s.title })),
    notes,
  }
}

