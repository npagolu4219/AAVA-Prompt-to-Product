function collectionDecl(s: ScreenCtx, opts: ExportOptions, indent: string, wrap: (table: string, id: string) => string) {
  const ids = Object.keys(s.ir.seed.collections)
  if (!ids.length) return ''
  const live = new Map(s.ir.live.map((l) => [l.id, l.table]))
  return ids.map((id) => `${indent}${id}: ${opts.includeData && live.has(id) ? wrap(live.get(id)!, id) : `seed.collections.${id}`},`).join('\n')
}

